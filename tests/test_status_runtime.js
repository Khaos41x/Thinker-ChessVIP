const assert = require('node:assert/strict');
require('../frontend/external_config/status-runtime');
let now = 0;
const health = globalThis.ThinkerStatus.health({now:()=>now});
health.success();
assert.equal(health.delay(),2000);
now=2000; assert.equal(health.failure(),false); assert.equal(health.delay(),2000);
now=4000; assert.equal(health.failure(),false); assert.equal(health.delay(),4000);
now=8000; assert.equal(health.failure(),true); assert.equal(health.delay(),8000);
now=16000; health.failure(); assert.equal(health.delay(),16000);
now=32000; health.failure(); assert.equal(health.delay(),30000);
health.success(); assert.equal(health.snapshot().failures,0); assert.equal(health.delay(),2000);
health.reset(); assert.equal(health.due(),true);
let mutations=0, value='Ready';
const node={get textContent(){return value;},set textContent(next){mutations++;value=next;}};
globalThis.ThinkerStatus.text(node,'Ready'); assert.equal(mutations,0);
globalThis.ThinkerStatus.text(node,'Error'); assert.equal(mutations,1);
globalThis.ThinkerStatus.text(node,'Error'); assert.equal(mutations,1);
console.log('PASS status difference setters, 3 failures + 6s hysteresis, backoff and recovery');
